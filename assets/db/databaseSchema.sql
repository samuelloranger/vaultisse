CREATE
OR REPLACE FUNCTION enforce_customer_id_null()
RETURNS TRIGGER AS $$
BEGIN
  -- Si el nuevo status NO es 2, seteamos customer_id a NULL
  IF
NEW.status != 2 THEN
    NEW.customer_id := NULL;
END IF;

RETURN NEW;
END;
$$
LANGUAGE plpgsql;

