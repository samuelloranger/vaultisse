    book_id     INT                                     NOT NULL,
    created_by  INT,
    code        CHAR(10) UNIQUE                         NOT NULL,
    -- 0: available, 1: not available, 2: booked, 3: damaged
    status      SMALLINT CHECK (status IN (0, 1, 2, 3)) NOT NULL DEFAULT 0,
